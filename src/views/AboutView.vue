      <h1>What does Silloker do?</h1>
      <p class="lead">
        Silloker is a digital platform that opens creative avenues into studying Korea’s Chosŏn
        dynasty (1392–1910).
      </p>

      <p>
        Its title takes after <i>sillok</i> 實錄 (“veritable records”), a compilation of Chosŏn
        court annals that ran for five centuries, covering topics as varied as diplomacy, economy,
        religion, quotidian life, and natural phenomena. This is a staggering 49,646,667
        characters and 1,894 books, fully digitized. But it is only a sliver of administrative
        records available in digital form, including the Records of the <i>Border Defense
        Council</i> 備邊司謄錄 (<i>Pibyŏnsa tŭngnok</i>) and the <i>Diaries of the Royal
        Secretariat</i> 承政院日記 (<i>Sŭngjŏngwŏn ilgi</i>).
      </p>

      <p>
        Silloker joins these archives in a single platform and offers tools for exploratory data
        analysis. Users can query across multiple archives, download search results, and graph
        the frequency of search hits throughout the five-century dynasty. For Korean studies and
        beyond, the platform offers a model for curating chronicle data that combines traditional
        search with built-in analysis.
      </p>

